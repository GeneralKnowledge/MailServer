#!/usr/bin/env bash
# Apply branding/ to the invite website and (if present) mailcow's SOGo.
# Usage: scripts/apply-branding.sh [mailcow-dir]   (default /opt/mailcow-dockerized)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MAILCOW_DIR="${1:-/opt/mailcow-dockerized}"
# shellcheck disable=SC1091
source "$ROOT/branding/brand.env"

python3 - "$ROOT" "$MAILCOW_DIR" "$BRAND_COLOR" "$BRAND_ACCENT" <<'PY'
import os, sys, shutil
root, mc, color, accent = sys.argv[1:5]

def rgb(h):
    h = h.lstrip("#"); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def hexc(c): return "".join(f"{max(0,min(255,round(v))):02X}" for v in c)
def mix(a, b, t): return tuple(x + (y - x) * t for x, y in zip(a, b))
def lum(c):
    def ch(v):
        v /= 255; return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in c); return 0.2126*r + 0.7152*g + 0.0722*b

def palette(base):
    """Material-style 50..900 + A100..A700 around the base colour at 500."""
    c = rgb(base); W, K = (255,)*3, (0,)*3
    p = {"50": mix(c, W, .9), "100": mix(c, W, .75), "200": mix(c, W, .55), "300": mix(c, W, .35),
         "400": mix(c, W, .15), "500": c, "600": mix(c, K, .12), "700": mix(c, K, .25),
         "800": mix(c, K, .38), "900": mix(c, K, .5), "A100": mix(c, W, .6), "A200": mix(c, W, .3),
         "A400": c, "A700": mix(c, K, .2)}
    out = {k: hexc(v) for k, v in p.items()}
    out["contrastDefaultColor"] = "light"
    out["contrastDarkColors"] = [k for k, v in p.items() if lum(v) > 0.45]
    return out

contrast = "#ffffff" if lum(rgb(color)) < 0.45 else "#111111"
css = f"""/* Generated by scripts/apply-branding.sh from branding/brand.env. Do not edit. */
:root {{
  --brand: {color};
  --brand-dark: #{hexc(mix(rgb(color), (0,0,0), .2))};
  --brand-contrast: {contrast};
  --accent: {accent};
}}
"""
static = os.path.join(root, "registration/app/static")
open(os.path.join(static, "brand.css"), "w").write(css)
shutil.copy(os.path.join(root, "branding/logo.svg"), os.path.join(static, "logo.svg"))
shutil.copy(os.path.join(root, "branding/logo.svg"), os.path.join(static, "favicon.svg"))
print("invite website: brand.css and logos updated")

import json
# Dark background palette. Every hue is dark: SOGo paints panes with several
# background hues (sidebar 300, reading pane 200, list A400), so a light-to-dark
# scale leaves lavender panes in dark mode.
# 500 stays mid-tone: Angular Material uses it for hover tints and SOGo for
# empty-state text.
night = {"50": "3A3245", "100": "342C3E", "200": "1C1722", "300": "201A27", "400": "2B2434",
         "500": "8F849E", "600": "1F1A26", "700": "1A1620", "800": "17131C", "900": "141118",
         "A100": "2B2434", "A200": "1F1A26", "A400": "141118", "A700": "0E0B11",
         "contrastDefaultColor": "light", "contrastDarkColors": []}
theme = f"""/* Generated by scripts/apply-branding.sh (MailServer repo). Do not edit here. */
(function() {{
  'use strict';
  angular.module('SOGo.Common').config(configure);
  configure.$inject = ['$mdThemingProvider'];
  function configure($mdThemingProvider) {{
    // Dark mode, same origin as the mailcow login page and the invite site:
    // the mailcow login toggle ("mailcow_theme"), else the invite site's
    // choice ("mail-theme"), else the device setting.
    var dark = false;
    try {{
      var pref = window.localStorage.getItem('mailcow_theme') ||
                 window.localStorage.getItem('mail-theme');
      dark = (pref === 'dark') || ((!pref || pref === 'auto') &&
             window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches);
    }} catch (e) {{}}
    $mdThemingProvider.definePalette('brand-primary', {json.dumps(palette(color))});
    $mdThemingProvider.definePalette('brand-accent', {json.dumps(palette(accent))});
    $mdThemingProvider.definePalette('brand-night', {json.dumps(night)});
    var theme = $mdThemingProvider.theme('default')
      .primaryPalette('brand-primary', {{'default': '500', 'hue-1': '300', 'hue-2': '700', 'hue-3': 'A700'}})
      .accentPalette('brand-accent', {{'default': '500', 'hue-1': '300', 'hue-2': '700', 'hue-3': 'A700'}});
    if (dark) {{
      theme.backgroundPalette('brand-night').dark();
      document.documentElement.classList.add('mail-dark');
      // Plum text (quota line, links) is too dark on the dark panes.
      var st = document.createElement('style');
      // SOGo keeps the open message on a white card (mail bodies assume a light
      // background), so recipient chips there need light colours too.
      st.textContent = '.mail-dark .md-fg.md-primary {{ color: #{hexc(mix(rgb(color), (255,255,255), .55))} !important; }}' +
        '.mail-dark .view-detail md-card md-chip {{ background: #ECE7F1; color: #1F1A26; }}';
      document.head.appendChild(st);
    }} else {{
      theme.backgroundPalette('grey');
    }}
    $mdThemingProvider.generateThemesOnDemand(false);
  }}
}})();
"""
# mailcow's own login page (mail.<domain>/ and /SOGo both land there) and
# admin UI. 0081-custom-mailcow.css is mailcow's documented, git-ignored hook.
# It is bundled before 014-mailcow.css, hence the doubled :root selector.
brand_dark = "#" + hexc(mix(rgb(color), (0,0,0), .2))
mc_css_text = f"""/* Generated by scripts/apply-branding.sh (MailServer repo). Do not edit here. */
:root:root {{
  --mc-primary: {color};
  --mc-primary-border: {brand_dark};
  --mc-login-user: {color};
}}
.login-user .btn-success,
.login-user .btn-success:hover,
.login-user .btn-success:focus,
.login-user .btn-success:active {{
  background-color: {color} !important;
  border-color: {brand_dark} !important;
  color: {contrast} !important;
}}
.login-user .btn-success:hover {{ background-color: {brand_dark} !important; }}
.login-card a {{ color: {color}; }}
.mailcow-logo img {{ max-width: 100%; height: auto; }}
/* mailcow's dark mode adds <link id="dark-mode-theme">. */
html:has(#dark-mode-theme) .login-card a {{ color: {accent}; }}
"""
web_gen = os.path.join(root, "infrastructure/mailcow/configuration/web")
os.makedirs(web_gen, exist_ok=True)
open(os.path.join(web_gen, "0081-custom-mailcow.css"), "w").write(mc_css_text)
mc_web = os.path.join(mc, "data/web/css/build")
if os.path.isdir(mc_web):
    shutil.copy(os.path.join(web_gen, "0081-custom-mailcow.css"), os.path.join(mc_web, "0081-custom-mailcow.css"))
    print(f"mailcow UI: stylesheet copied to {mc_web}")

gen = os.path.join(root, "infrastructure/mailcow/configuration/sogo")
os.makedirs(gen, exist_ok=True)
open(os.path.join(gen, "custom-theme.js"), "w").write(theme)
sogo = os.path.join(mc, "data/conf/sogo")
if os.path.isdir(sogo):
    shutil.copy(os.path.join(gen, "custom-theme.js"), os.path.join(sogo, "custom-theme.js"))
    shutil.copy(os.path.join(root, "branding/logo-full.svg"), os.path.join(sogo, "custom-fulllogo.svg"))
    shutil.copy(os.path.join(root, "branding/logo.svg"), os.path.join(sogo, "custom-shortlogo.svg"))
    # SOGo links a precompiled css/theme-default.css (its own blue-green) that
    # outranks the palette from custom-theme.js. docker-compose.override.yml
    # mounts this empty file over it.
    open(os.path.join(sogo, "custom-theme-default.css"), "w").write(
        "/* Empty on purpose: SOGo's precompiled theme is replaced by custom-theme.js. */\n")
    print(f"SOGo: theme and logos copied to {sogo}")
else:
    print(f"SOGo: {sogo} not found, generated theme left in {gen}")
PY

if [ -d "$MAILCOW_DIR/data/conf/sogo" ]; then
  cd "$MAILCOW_DIR"
  if ! grep -qs 'custom-theme-default.css' docker-compose.override.yml; then
    echo "WARNING: $MAILCOW_DIR/docker-compose.override.yml doesn't mount custom-theme-default.css,"
    echo "         so SOGo keeps its own colours. Copy or merge"
    echo "         $ROOT/infrastructure/mailcow/configuration/docker-compose.override.yml"
    echo "         and run: docker compose up -d sogo-mailcow"
  fi

  # mailcow login page: logos and names live in Redis (what System > Configuration >
  # Options > Customize writes).
  if docker compose ps --status running --services 2>/dev/null | grep -qx redis-mailcow; then
    # rset KEY < value. The Redis password is taken from the container's own
    # REDISPASS and the value comes on stdin, so neither shows up in `ps` on
    # the host (redis-cli -a would put the password on the command line).
    rset() {
      docker compose exec -T redis-mailcow sh -c \
        '[ -z "$REDISPASS" ] || export REDISCLI_AUTH="$REDISPASS"; exec redis-cli -x SET "$1"' sh "$1" >/dev/null
    }
    printf '%s' "data:image/svg+xml;base64,$(base64 -w0 "$ROOT/branding/logo-full.svg")" | rset MAIN_LOGO
    printf '%s' "data:image/svg+xml;base64,$(base64 -w0 "$ROOT/branding/logo-full-dark.svg")" | rset MAIN_LOGO_DARK
    printf '%s' "$BRAND_NAME" | rset TITLE_NAME
    printf '%s' "$BRAND_NAME" | rset MAIN_NAME
    echo "mailcow UI: logos and names set"
  else
    echo "mailcow UI: redis-mailcow not running, logos and names not set (re-run once mailcow is up)"
  fi

  docker compose restart memcached-mailcow sogo-mailcow
  echo "Restarted SOGo. Rebuild the invite site: (cd $ROOT/infrastructure/registration && docker compose up -d --build)"
fi
